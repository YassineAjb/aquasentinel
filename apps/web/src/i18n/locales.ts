export const dictionaries: Record<Locale, Dict> = { en, ar, ja };

export function translate(
  locale: Locale,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const dict = dictionaries[locale] || dictionaries.en;
  let text = dict[key] ?? dictionaries.en[key] ?? key;
  if (vars) {
    const count = typeof vars.count === 'number' ? vars.count : undefined;
    if (count != null && count !== 1) {
      const plural = dict[`${key}_other`] ?? dictionaries.en[`${key}_other`];
      if (plural) text = plural;
    }
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/** Map UI locale → assistant / speech codes */
export function assistantLangFor(locale: Locale): string {
  if (locale === 'ar') return 'ar-tn';
  if (locale === 'ja') return 'ja';
  return 'en';
}
